public class BitEx {
    public static void main(String[] args) {
        int a = 12; // 1100
        int b = 10; // 1010
        System.out.println(a & b);
        System.out.println(a | b);
        System.out.println(a ^ b);
        System.out.println(~a);
        System.out.println(a << 2);
        System.out.println(a >> 2);
        System.out.println(-8 >>> 28);
    }
}
